package com.farshadghanzanfari.promoneymanager.core.domain

import com.farshadghanzanfari.promoneymanager.core.model.AccountId
import com.farshadghanzanfari.promoneymanager.core.model.CategoryId
import com.farshadghanzanfari.promoneymanager.core.model.CurrencyCode
import com.farshadghanzanfari.promoneymanager.core.model.MatchType
import com.farshadghanzanfari.promoneymanager.core.model.MerchantRule
import com.farshadghanzanfari.promoneymanager.core.model.Money
import com.farshadghanzanfari.promoneymanager.core.model.Transaction
import com.farshadghanzanfari.promoneymanager.core.model.TransactionKind
import com.google.common.truth.Truth.assertThat
import java.time.LocalDate
import org.junit.Test

class SmartCategorizationServiceTest {
    private val aed = CurrencyCode.of("AED")
    private val accountId = AccountId("daily-card")

    @Test
    fun learnsCandidateRulesFromRepeatedCategorizedMerchants() {
        val candidates = SmartCategorizationService.learnRuleCandidates(
            transactions = listOf(
                transaction("t1", "CAREFUL MARKET BRANCH 1", "food", "groceries"),
                transaction("t2", "Careful Market Branch 2", "food", "groceries"),
                transaction("t3", "CAREFUL MARKET BRANCH 3", "food", "groceries"),
                transaction("t4", "One Off Cafe", "food", "coffee"),
            ),
            existingRules = emptyList(),
            minimumSamples = 3,
        )

        assertThat(candidates).hasSize(1)
        assertThat(candidates.single().pattern).isEqualTo("CAREFUL MARKET")
        assertThat(candidates.single().categoryId).isEqualTo(CategoryId("food"))
        assertThat(candidates.single().subcategoryId).isEqualTo(CategoryId("groceries"))
        assertThat(candidates.single().sampleCount).isEqualTo(3)
        assertThat(candidates.single().confidence).isAtLeast(0.85)
    }

    @Test
    fun doesNotDuplicateExistingManualRules() {
        val existing = MerchantRule(
            id = "manual-careful",
            pattern = "CAREFUL MARKET",
            matchType = MatchType.CONTAINS,
            categoryId = CategoryId("food"),
            subcategoryId = CategoryId("groceries"),
            kind = TransactionKind.EXPENSE,
            isAutoGenerated = false,
        )

        val candidates = SmartCategorizationService.learnRuleCandidates(
            transactions = listOf(
                transaction("t1", "Careful Market Branch 1", "food", "groceries"),
                transaction("t2", "Careful Market Branch 2", "food", "groceries"),
                transaction("t3", "Careful Market Branch 3", "food", "groceries"),
            ),
            existingRules = listOf(existing),
            minimumSamples = 2,
        )

        assertThat(candidates).isEmpty()
    }

    @Test
    fun previewOnlyAffectsUncategorizedTransactions() {
        val rule = MerchantRule(
            id = "rule-careem",
            pattern = "CAREEM HALA",
            categoryId = CategoryId("transportation"),
            subcategoryId = CategoryId("taxi"),
            kind = TransactionKind.EXPENSE,
            confidence = 0.91,
        )

        val previews = SmartCategorizationService.previewCategorization(
            transactions = listOf(
                transaction("uncategorized", "CAREEM HALA RIDE"),
                transaction("categorized", "CAREEM HALA RIDE", "business"),
            ),
            rules = listOf(rule),
        )

        assertThat(previews).hasSize(1)
        assertThat(previews.single().transactionId.value).isEqualTo("uncategorized")
        assertThat(previews.single().suggestedCategoryId).isEqualTo(CategoryId("transportation"))
        assertThat(previews.single().suggestedSubcategoryId).isEqualTo(CategoryId("taxi"))
        assertThat(previews.single().confidence).isEqualTo(0.91)
    }

    @Test
    fun bulkApplyProducesAtomicPlanForSelectedPreviews() {
        val previews = listOf(
            CategorizationPreview(
                transactionId = transaction("t1", "CAREEM HALA").id,
                normalizedMerchant = "CAREEM HALA",
                suggestedCategoryId = CategoryId("transportation"),
                suggestedSubcategoryId = CategoryId("taxi"),
                confidence = 0.91,
            ),
            CategorizationPreview(
                transactionId = transaction("t2", "AGODA").id,
                normalizedMerchant = "AGODA",
                suggestedCategoryId = CategoryId("travel"),
                confidence = 0.88,
            ),
        )

        val plan = SmartCategorizationService.createBulkApplyPlan(
            previews = previews,
            selectedTransactionIds = setOf(previews[0].transactionId),
        )

        assertThat(plan.operations).hasSize(1)
        assertThat(plan.operations.single().transactionId).isEqualTo(previews[0].transactionId)
        assertThat(plan.operations.single().categoryId).isEqualTo(CategoryId("transportation"))
        assertThat(plan.isAtomic).isTrue()
    }

    private fun transaction(
        id: String,
        merchant: String,
        categoryId: String? = null,
        subcategoryId: String? = null,
    ): Transaction = Transaction.posting(
        id = id,
        accountId = accountId,
        amount = Money(1_000, aed),
        kind = TransactionKind.EXPENSE,
        localDate = LocalDate.parse("2026-06-10"),
        merchant = merchant,
        normalizedMerchant = MerchantNormalizer.normalize(merchant),
        categoryId = categoryId?.let(::CategoryId),
        subcategoryId = subcategoryId?.let(::CategoryId),
    )
}

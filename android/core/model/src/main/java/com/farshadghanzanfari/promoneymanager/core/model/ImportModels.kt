package com.farshadghanzanfari.promoneymanager.core.model

enum class MatchType {
    EXACT,
    CONTAINS,
}

data class MerchantRule(
    val id: String,
    val pattern: String,
    val matchType: MatchType = MatchType.CONTAINS,
    val categoryId: CategoryId,
    val subcategoryId: CategoryId? = null,
    val kind: TransactionKind = TransactionKind.EXPENSE,
    val confidence: Double = 0.7,
    val sampleCount: Int = 0,
    val isEnabled: Boolean = true,
    val accountId: AccountId? = null,
    val notePattern: String? = null,
    val minAmount: Money? = null,
    val maxAmount: Money? = null,
    val priority: Int = 0,
    val isAutoGenerated: Boolean = false,
) {
    init {
        require(pattern.isNotBlank()) { "Merchant rule pattern must not be blank." }
        require(confidence in 0.0..1.0) { "Merchant rule confidence must be between 0 and 1." }
        require(sampleCount >= 0) { "Merchant rule sample count must not be negative." }
    }
}

data class CategorySuggestion(
    val categoryId: CategoryId,
    val subcategoryId: CategoryId? = null,
    val kind: TransactionKind,
    val confidence: Double,
)

enum class ImportFormat {
    PDF,
    CSV,
    PLAIN_TEXT,
    PASTED_MESSAGE,
    XLSX,
    XLS,
}

data class ParsedImportTransaction(
    val localDate: java.time.LocalDate?,
    val merchant: String,
    val normalizedMerchant: String,
    val kind: TransactionKind,
    val amount: Money,
    val suggestedCategoryId: CategoryId? = null,
    val suggestedSubcategoryId: CategoryId? = null,
    val confidence: Double = 0.0,
    val isSelected: Boolean = true,
    val isDuplicate: Boolean = false,
    val isReviewOnly: Boolean = false,
    val sourceRow: Int? = null,
)

data class ImportReviewSaveCommand(
    val batchId: ImportBatchId,
    val sourceName: String,
    val accountId: AccountId,
    val rows: List<ParsedImportTransaction>,
)

data class ImportReviewSaveResult(
    val batchId: ImportBatchId,
    val savedCount: Int,
    val skippedCount: Int,
)

class ImportParseException(message: String) : RuntimeException(message)

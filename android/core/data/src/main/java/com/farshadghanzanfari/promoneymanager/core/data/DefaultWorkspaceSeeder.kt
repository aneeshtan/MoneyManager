package com.farshadghanzanfari.promoneymanager.core.data

import androidx.room.withTransaction
import com.farshadghanzanfari.promoneymanager.core.database.AccountEntity
import com.farshadghanzanfari.promoneymanager.core.database.AppDatabase
import com.farshadghanzanfari.promoneymanager.core.database.CategoryEntity
import com.farshadghanzanfari.promoneymanager.core.database.MerchantRuleEntity
import com.farshadghanzanfari.promoneymanager.core.database.ProfileEntity
import com.farshadghanzanfari.promoneymanager.core.domain.DefaultCategories
import com.farshadghanzanfari.promoneymanager.core.model.CurrencyCode
import javax.inject.Inject

class DefaultWorkspaceSeeder @Inject constructor(
    private val database: AppDatabase,
) {
    suspend fun seed(currency: CurrencyCode, displayName: String = "Local User") {
        database.withTransaction {
            val dao = database.financeDao()
            if (dao.countProfiles() > 0) return@withTransaction

            dao.upsertProfile(
                ProfileEntity(
                    id = "primary-user",
                    displayName = displayName,
                    baseCurrency = currency.value,
                    countryCode = null,
                    timeZoneId = null,
                ),
            )
            listOf(
                Triple("cash", "Cash", "CASH"),
                Triple("bank", "Bank Account", "BANK"),
                Triple("credit-card", "Credit Card", "CREDIT_CARD"),
                Triple("savings", "Savings", "BANK"),
            ).forEachIndexed { index, (id, name, type) ->
                dao.upsertAccount(
                    AccountEntity(
                        id = id,
                        profileId = "primary-user",
                        name = name,
                        currencyCode = currency.value,
                        openingBalanceMinor = 0,
                        type = type,
                        isArchived = false,
                        sortOrder = index,
                    ),
                )
            }

            DefaultCategories.all.map { definition ->
                CategoryEntity(
                    id = definition.id.value,
                    profileId = "primary-user",
                    name = definition.name,
                    kind = definition.kind.name,
                    parentId = definition.parentId?.value,
                    sortOrder = definition.sortOrder,
                    isArchived = false,
                )
            }.forEach { dao.upsertCategory(it) }

            dao.upsertMerchantRule(
                MerchantRuleEntity(
                    id = "rule-amazon-grocery",
                    profileId = "primary-user",
                    pattern = "AMAZON GROCERY",
                    matchType = "CONTAINS",
                    categoryId = "category-food",
                    subcategoryId = "category-groceries",
                    kind = "EXPENSE",
                    confidence = 0.75,
                    sampleCount = 1,
                    isEnabled = true,
                    createdAt = "1970-01-01T00:00:00Z",
                    accountId = null,
                    notePattern = null,
                    minAmountMinor = null,
                    maxAmountMinor = null,
                    amountCurrencyCode = null,
                    priority = 0,
                    isAutoGenerated = true,
                ),
            )
        }
    }
}

    @Test
    fun storesAndClearsBudgets() = runTest {
        seedProfileAndAccount()
        database.financeDao().upsertCategory(
            CategoryEntity("food", "profile", "Food", "EXPENSE", null, 1, false),
        )
        database.financeDao().upsertCategory(
            CategoryEntity("groceries", "profile", "Groceries", "EXPENSE", "food", 2, false),
        )
        database.financeDao().upsertBudget(
            BudgetEntity(
                id = "budget-food-june",
                profileId = "profile",
                categoryId = "food",
                subcategoryId = "groceries",
                month = "2026-06",
                amountMinor = 50_000,
                currencyCode = "AED",
                rolloverEnabled = true,
                isArchived = false,
            ),
        )

        val budget = database.financeDao().observeBudgets().first().single()

        assertThat(budget.month).isEqualTo("2026-06")
        assertThat(budget.rolloverEnabled).isTrue()

        database.financeDao().setBudgetArchived("budget-food-june", true)
        assertThat(database.financeDao().observeBudgets().first().single().isArchived).isTrue()

        database.clearWorkspace()
        assertThat(database.financeDao().countBudgets()).isEqualTo(0)
    }

    @Test
    fun storesArchivesAndClearsPlanningTables() = runTest {
        seedProfileAndAccount()
        database.financeDao().upsertCategory(
            CategoryEntity("transportation", "profile", "Transportation", "EXPENSE", null, 1, false),
        )
        database.financeDao().upsertScheduledTransaction(
            ScheduledTransactionEntity(
                id = "schedule-careem",
                profileId = "profile",
                accountId = "account",
                amountMinor = 5_800,
                currencyCode = "AED",
                kind = "EXPENSE",
                merchant = "Careem Hala",
                normalizedMerchant = "CAREEM HALA",
                categoryId = "transportation",
                subcategoryId = null,
                note = "airport ride",
                frequency = "MONTHLY",
                nextDate = "2026-07-15",
                lastRunDate = null,
                status = "ACTIVE",
                reminderEnabled = true,
            ),
        )
        database.financeDao().upsertSavingsGoal(
            SavingsGoalEntity(
                id = "goal-emergency",
                profileId = "profile",
                name = "Emergency fund",
                targetAmountMinor = 1_000_000,
                currentAmountMinor = 125_000,
                currencyCode = "AED",
                targetDate = "2026-12-31",
                isArchived = false,
            ),
        )
        database.financeDao().upsertSavingsGoalContribution(
            SavingsGoalContributionEntity(
                id = "goal-contribution-1",
                goalId = "goal-emergency",
                amountMinor = 25_000,
                currencyCode = "AED",
                direction = "CONTRIBUTION",
                localDate = "2026-07-11",
                note = "monthly transfer",
            ),
        )
        database.financeDao().upsertDebtPayoffPlan(
            DebtPayoffPlanEntity(
                id = "debt-card",
                profileId = "profile",
                name = "Credit card payoff",
                originalBalanceMinor = 1_000_000,
                currentBalanceMinor = 600_000,
                currencyCode = "AED",
                annualInterestRateBasisPoints = 0,
                minimumPaymentMinor = 50_000,
                extraPaymentMinor = 25_000,
                strategy = "SNOWBALL",
                isArchived = false,
            ),
        )

        assertThat(database.financeDao().observeScheduledTransactions().first().single().merchant)
            .isEqualTo("Careem Hala")
        assertThat(database.financeDao().observeSavingsGoals().first().single().name)
            .isEqualTo("Emergency fund")
        assertThat(database.financeDao().observeSavingsGoalContributions().first().single().note)
            .isEqualTo("monthly transfer")
        assertThat(database.financeDao().observeDebtPayoffPlans().first().single().strategy)
            .isEqualTo("SNOWBALL")

        database.financeDao().setScheduledTransactionArchived("schedule-careem", true)
        database.financeDao().setSavingsGoalArchived("goal-emergency", true)
        database.financeDao().setDebtPayoffPlanArchived("debt-card", true)

        assertThat(database.financeDao().observeScheduledTransactions().first().single().status)
            .isEqualTo("PAUSED")
        assertThat(database.financeDao().observeSavingsGoals().first().single().isArchived).isTrue()
        assertThat(database.financeDao().observeDebtPayoffPlans().first().single().isArchived).isTrue()

        database.clearWorkspace()

        assertThat(database.financeDao().countScheduledTransactions()).isEqualTo(0)
        assertThat(database.financeDao().countSavingsGoals()).isEqualTo(0)
        assertThat(database.financeDao().countSavingsGoalContributions()).isEqualTo(0)
        assertThat(database.financeDao().countDebtPayoffPlans()).isEqualTo(0)
    }

    @Test
    fun storesRichTransactionRelations() = runTest {
        seedProfileAndAccount()
        database.financeDao().upsertCategory(
            CategoryEntity("food", "profile", "Food", "EXPENSE", null, 1, false),
        )
        database.financeDao().upsertTag(
            TagEntity("business", "profile", "Business", "8151D1", "2026-07-10T10:00:00Z"),
        )
        database.financeDao().upsertTransactions(
            listOf(
                TransactionEntity(
                    id = "txn",
                    accountId = "account",
                    localDate = "2026-07-10",
                    amountMinor = 1250,
                    currencyCode = "AED",
                    kind = "EXPENSE",
                    merchant = "Amazon Grocery Dubai",
                    normalizedMerchant = "AMAZON GROCERY",
                    note = "weekly food",
                    categoryId = "food",
                    subcategoryId = null,
                    transferId = null,
                    transferDirection = null,
                    importBatchId = "batch",
                    rawDescription = "AMAZON GROCERY DUBAI",
                    sourceName = "statement.pdf",
                    sourceRow = 4,
                ),
            ),
        )
        database.financeDao().upsertTransactionTagRefs(
            listOf(TransactionTagCrossRef("txn", "business")),
        )
        database.financeDao().upsertAttachment(
            TransactionAttachmentEntity(
                id = "attachment",
                transactionId = "txn",
                fileName = "receipt.jpg",
                originalFileName = "IMG_1000.JPG",
                contentType = "image/jpeg",
                createdAt = "2026-07-10T10:00:00Z",
            ),
        )

        val transaction = database.financeDao().observeTransactions().first().single()

        assertThat(transaction.categoryId).isEqualTo("food")
        assertThat(transaction.sourceName).isEqualTo("statement.pdf")
        assertThat(database.financeDao().getTagIdsForTransaction("txn")).containsExactly("business")
        assertThat(database.financeDao().observeAttachments("txn").first().single().originalFileName)
            .isEqualTo("IMG_1000.JPG")
    }

    @Test
    fun archivesAndRestoresAccountsAndCategories() = runTest {
        seedProfileAndAccount()
        database.financeDao().upsertCategory(
            CategoryEntity("food", "profile", "Food", "EXPENSE", null, 1, false),
        )

        database.financeDao().setAccountArchived("account", true)
        database.financeDao().setCategoryArchived("food", true)

        assertThat(database.financeDao().observeAccounts().first().single().isArchived).isTrue()
        assertThat(database.financeDao().observeCategories().first().single().isArchived).isTrue()

        database.financeDao().setAccountArchived("account", false)
        database.financeDao().setCategoryArchived("food", false)

        assertThat(database.financeDao().observeAccounts().first().single().isArchived).isFalse()
        assertThat(database.financeDao().observeCategories().first().single().isArchived).isFalse()
    }

    @Test
    fun deletingWorkspaceRemovesParityTables() = runTest {
        seedProfileAndAccount()
        database.financeDao().upsertCategory(
            CategoryEntity("food", "profile", "Food", "EXPENSE", null, 1, false),
        )
        database.financeDao().upsertTag(
            TagEntity("business", "profile", "Business", "8151D1", "2026-07-10T10:00:00Z"),
        )
        database.financeDao().upsertTransactions(
            listOf(
                TransactionEntity(
                    id = "txn",
                    accountId = "account",
                    localDate = "2026-07-10",
                    amountMinor = 1250,
                    currencyCode = "AED",
                    kind = "EXPENSE",

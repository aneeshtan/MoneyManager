    }

    private suspend fun seedProfileAndAccount() {
        database.financeDao().upsertProfile(
            ProfileEntity("profile", "Local User", "AED", "AE", "Asia/Dubai"),
        )
        database.financeDao().upsertAccount(
            AccountEntity("account", "profile", "Daily Card", "AED", 0, "BANK", false, 0),
        )
    }

    private suspend fun workspaceTableCounts(): Map<String, Int> {
        val dao = database.financeDao()
        return mapOf(
            "profiles" to dao.countProfiles(),
            "accounts" to dao.countAccounts(),
            "categories" to dao.countCategories(),
            "tags" to dao.countTags(),
            "transactions" to dao.countTransactions(),
            "transaction_tags" to dao.countTransactionTags(),
            "transaction_attachments" to dao.countAttachments(),
            "merchant_rules" to dao.countMerchantRules(),
            "budgets" to dao.countBudgets(),
            "scheduled_transactions" to dao.countScheduledTransactions(),
            "savings_goals" to dao.countSavingsGoals(),
            "savings_goal_contributions" to dao.countSavingsGoalContributions(),
            "debt_payoff_plans" to dao.countDebtPayoffPlans(),
        )
    }

    private fun appTableNames(): List<String> =
        database.openHelper.readableDatabase
            .query("SELECT name FROM sqlite_master WHERE type = 'table'")
            .use { cursor ->
                buildList {
                    while (cursor.moveToNext()) {
                        val name = cursor.getString(0)
                        if (!name.startsWith("android_") &&
                            !name.startsWith("room_") &&
                            !name.startsWith("sqlite_")
                        ) {
                            add(name)
                        }
                    }
                }
            }
}

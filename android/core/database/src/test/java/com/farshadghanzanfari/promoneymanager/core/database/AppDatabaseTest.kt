package com.farshadghanzanfari.promoneymanager.core.database

import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.google.common.truth.Truth.assertThat
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.Config
import org.robolectric.RobolectricTestRunner

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class AppDatabaseTest {
    private lateinit var database: AppDatabase

    @Before
    fun setUp() {
        database = Room.inMemoryDatabaseBuilder(
            ApplicationProvider.getApplicationContext(),
            AppDatabase::class.java,
        ).allowMainThreadQueries().build()
    }

    @After
    fun tearDown() = database.close()

    @Test
    fun observesAccountsInSortOrder() = runTest {
        database.financeDao().upsertProfile(
            ProfileEntity("profile", "Local User", "AED", "AE", "Asia/Dubai"),
        )
        database.financeDao().upsertAccount(
            AccountEntity("b", "profile", "Second", "AED", 0, "BANK", false, 2),
        )
        database.financeDao().upsertAccount(
            AccountEntity("a", "profile", "First", "AED", 0, "CASH", false, 1),
        )

        assertThat(database.financeDao().observeAccounts().first().map { it.id })
            .containsExactly("a", "b")
            .inOrder()
    }

    @Test
    fun deletingWorkspaceRemovesEveryFoundationTable() = runTest {
        database.financeDao().upsertProfile(
            ProfileEntity("profile", "Local User", "AED", "AE", "Asia/Dubai"),
        )
        database.financeDao().upsertAccount(
            AccountEntity("a", "profile", "Cash", "AED", 0, "CASH", false, 0),
        )

        database.clearWorkspace()

        val counts = workspaceTableCounts()

        assertThat(counts.keys).containsExactlyElementsIn(appTableNames())
        assertThat(counts.values).containsExactlyElementsIn(List(counts.size) { 0 })
    }


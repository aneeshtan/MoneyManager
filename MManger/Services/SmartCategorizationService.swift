import Foundation
import SwiftData

enum SmartCategorizationService {
    /// Learns one rule per merchant by majority vote over how that merchant was actually
    /// categorized.
    ///
    /// Grouping by merchant *and* label would emit competing rules for any merchant the
    /// user files under more than one category (groceries vs. gifts at the same
    /// supermarket), and whichever rule sorted first would win arbitrarily. Voting picks
    /// the dominant label and prices the rule by how dominant it was, so a merchant split
    /// evenly across categories produces a low-confidence rule instead of a coin flip.
    static func learnRules(
        from transactions: [FinanceTransaction],
        existingRules: [MerchantRule],
        minSamples: Int = 2,
        minConfidence: Double = 0.7,
        minPurity: Double = 0.5
    ) -> [MerchantRule] {
        let categorized = transactions.filter { $0.categoryName?.isEmpty == false }
        let grouped = Dictionary(grouping: categorized) { MerchantNormalizer.normalize($0.normalizedMerchant) }

        let existingPatterns = Set(existingRules.filter { !$0.isAutoGenerated }.map { MerchantNormalizer.normalize($0.pattern) })
        var newRules: [MerchantRule] = []

        for (normalizedMerchant, samples) in grouped {
            guard !normalizedMerchant.isEmpty,
                  samples.count >= minSamples,
                  !existingPatterns.contains(normalizedMerchant) else { continue }

            var votes: [RuleLabel: Int] = [:]
            for sample in samples {
                let label = RuleLabel(
                    categoryName: sample.categoryName ?? "",
                    subcategoryName: sample.subcategoryName,
                    kind: sample.kind
                )
                votes[label, default: 0] += 1
            }
            // Ties break on the label text so the same input always yields the same rule.
            guard let winner = votes
                .max(by: { ($0.value, $1.key.sortKey) < ($1.value, $0.key.sortKey) }) else { continue }

            let purity = Double(winner.value) / Double(samples.count)
            guard purity >= minPurity else { continue }

            newRules.append(
                MerchantRule(
                    pattern: shortestDistinctPattern(for: normalizedMerchant, in: samples),
                    matchType: .contains,
                    categoryName: winner.key.categoryName,
                    subcategoryName: winner.key.subcategoryName,
                    kind: winner.key.kind,
                    confidence: min(0.95, minConfidence + (purity - minPurity) * 0.5),
                    sampleCount: winner.value,
                    isAutoGenerated: true
                )
            )
        }

        return newRules.sorted { $0.sampleCount > $1.sampleCount }
    }

    /// Applies the provided rules to all uncategorized transactions and returns how many were updated.
    static func applyRules(
        to transactions: [FinanceTransaction],
        rules: [MerchantRule]
    ) -> Int {
        let snapshots = rules.map(MerchantRuleSnapshot.init)
        var updated = 0
        for transaction in transactions where transaction.categoryName?.isEmpty != false {
            guard let suggestion = CategoryMatcher.match(
                merchant: transaction.merchant,
                accountName: transaction.accountName,
                note: transaction.note,
                amount: transaction.amount,
                ruleSnapshots: snapshots,
                fallbackKind: transaction.kind
            ) else { continue }
            transaction.categoryName = suggestion.category
            transaction.subcategoryName = suggestion.subcategory
            transaction.kind = suggestion.kind
            transaction.updatedAt = .now
            updated += 1
        }
        return updated
    }

    /// Returns a preview of which uncategorized transactions would be affected by the rules.
    static func preview(
        for transactions: [FinanceTransaction],
        rules: [MerchantRule]
    ) -> [CategorizationPreview] {
        let snapshots = rules.map(MerchantRuleSnapshot.init)
        return transactions.compactMap { transaction in
            guard transaction.categoryName?.isEmpty != false else { return nil }
            guard let suggestion = CategoryMatcher.match(
                merchant: transaction.merchant,
                accountName: transaction.accountName,
                note: transaction.note,
                amount: transaction.amount,
                ruleSnapshots: snapshots,
                fallbackKind: transaction.kind
            ) else { return nil }
            return CategorizationPreview(
                transaction: transaction,
                suggestedCategory: suggestion.category,
                suggestedSubcategory: suggestion.subcategory,
                confidence: suggestion.confidence
            )
        }
    }

    private static func shortestDistinctPattern(for normalizedMerchant: String, in samples: [FinanceTransaction]) -> String {
        let words = normalizedMerchant.split(separator: " ").map(String.init)
        guard words.count > 1 else { return normalizedMerchant }
        for length in 1..<words.count {
            let candidate = words.prefix(length).joined(separator: " ")
            let matches = samples.filter { MerchantNormalizer.normalize($0.normalizedMerchant).contains(candidate) }
            if matches.count == samples.count {
                return candidate
            }
        }
        return normalizedMerchant
    }
}

private struct RuleLabel: Hashable {
    var categoryName: String
    var subcategoryName: String?
    var kind: TransactionKind

    var sortKey: String { "\(categoryName)|\(subcategoryName ?? "")|\(kind.rawValue)" }
}

struct CategorizationPreview: Identifiable {
    let id = UUID()
    var transaction: FinanceTransaction
    var suggestedCategory: String
    var suggestedSubcategory: String?
    var confidence: Double
}
